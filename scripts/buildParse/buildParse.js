import build from '../build/build.js';
import path from 'node:path';

// =====================================================================================================================
//  D E C L A R A T I O N S
// =====================================================================================================================
const OUTPUT_DIR = path.resolve(path.join(import.meta.dirname, '..', '..', 'dev')); // not docs!
const PREFIX = '//Source:https://github.com/Aurelain/oe-wiki/tree/main/src/parse';

// =====================================================================================================================
//  P U B L I C
// =====================================================================================================================
/**
 *
 */
async function buildParse() {
    try {
        await build('src/parse/parse.js', '-o', OUTPUT_DIR, '--prefix', PREFIX);
    } catch (e) {
        console.error('Build failed!');
    }
}

// =====================================================================================================================
//  R U N
// =====================================================================================================================
buildParse();
