/**
 *
 */
async function planner() {
    const root = document.querySelector('.planner');
    if (!root) {
        return;
    }

    const bgUrl = root.querySelector('.background img').src;
    let html = HTML.replace('@bgUrl', bgUrl);
    root.innerHTML = html;
}

// =====================================================================================================================
//  P R I V A T E
// =====================================================================================================================

// =====================================================================================================================
//  R U N
// =====================================================================================================================
planner();
