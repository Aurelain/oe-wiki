/**
 *
 */
function assume(condition, ...message) {
    if (!condition) {
        throw new Error(stringify(message));
    }
}

// =====================================================================================================================
//  E X P O R T
// =====================================================================================================================
/**
 *
 */
function stringify(list) {
    const lines = [];
    for (const arg of list) {
        lines.push(typeof arg === 'object' ? JSON.stringify(arg, null, 4) : arg);
    }
    return lines.join('\n');
}

// =====================================================================================================================
//  E X P O R T
// =====================================================================================================================
export default assume;
