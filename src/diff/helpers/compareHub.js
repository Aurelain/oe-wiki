import compareDef from './compareDef.js';

// =====================================================================================================================
//  P U B L I C
// =====================================================================================================================
/**
 *
 */
function compareHub(hubA = {}, hubB = {}) {
    const output = [];
    const ids = new Set([...Object.keys(hubA), ...Object.keys(hubB)]);
    for (const id of ids) {
        const list = compareDef(hubA[id], hubB[id]);
        for (const item of list) {
            output.push({
                id,
                ...item,
            });
        }
    }
    return output;
}

// =====================================================================================================================
//  E X P O R T
// =====================================================================================================================
export default compareHub;
