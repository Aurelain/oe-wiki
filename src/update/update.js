import mount from '../@shared/mount.jsx';
import App from './ui/App.jsx';

// =====================================================================================================================
//  P U B L I C
// =====================================================================================================================
/**
 *
 */
function update() {
    attemptMount() || window.addEventListener('load', attemptMount);
}

// =====================================================================================================================
//  P R I V A T E
// =====================================================================================================================
/**
 *
 */
function attemptMount() {
    const root = document.querySelector('#setup');
    if (!root) {
        return;
    }
    mount(App, root);
    return true;
}

// =====================================================================================================================
//  R U N
// =====================================================================================================================
update();
