function parse() {
    console.log('parse initialization');
    self.onmessage = onSelfMessage;
}

// =====================================================================================================================
//  P R I V A T E
// =====================================================================================================================
/**
 *
 */
function onSelfMessage(event) {
    const {data} = event;
    console.log('onSelfMessage', data);

    const result = sayHello(data);

    self.postMessage(result);
}

/**
 *
 */
function sayHello(text) {
    return text + '_hello';
}

// =====================================================================================================================
//  R U N
// =====================================================================================================================
parse();
