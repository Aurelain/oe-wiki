// =====================================================================================================================
//  D E C L A R A T I O N S
// =====================================================================================================================
let loggingFunction = console.log;

// =====================================================================================================================
//  P U B L I C
// =====================================================================================================================
/**
 *
 */
function log(...args) {
    loggingFunction(...args);
}

/**
 *
 */
function setLoggingFunction(fn) {
    loggingFunction = fn;
}

// =====================================================================================================================
//  E X P O R T
// =====================================================================================================================
export {setLoggingFunction};
export default log;
