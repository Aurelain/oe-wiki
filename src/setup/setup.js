/**
 *
 */
async function setup() {
    const root = document.getElementById('setup');
    if (!root) {
        return;
    }
    const configText = root.innerHTML;
    root.innerHTML = HTML;
    const config = parseConfig(configText);
    console.log('config:', config);
}

// =====================================================================================================================
//  P R I V A T E
// =====================================================================================================================
/**
 *
 */
function parseConfig(text) {
    try {
        return JSON.parse(text);
    } catch (e) {
        // log(e.message);
    }
}
// =====================================================================================================================
//  R U N
// =====================================================================================================================
setup();
